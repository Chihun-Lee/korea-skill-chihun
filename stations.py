"""코레일이 받아주는 역 목록 (v3.0 — KTX + SRT 통합).

2026-09-21 실측으로 전수 확인한 목록이다(코레일 조회 API에 역명을 그대로
넣어 "입력값오류(WRG200004)"가 나지 않는지 하나씩 확인). SRT 전용역
수서·동탄·평택지제도 코레일에서 정상 동작한다 — 통합 발매의 핵심.

별칭: 코레일은 "김천구미"(괄호 없음)·"신경주"(옛 이름)도 받지만, 목록에는
표준 표기 하나씩만 둔다.
"""
from __future__ import annotations

# 지역별 묶음 — UI가 이 순서/그룹대로 칩을 그린다
GROUPS: dict[str, list[str]] = {
    "수도권": ["수서", "서울", "용산", "청량리", "영등포", "광명", "행신", "동탄", "평택지제", "수원"],
    "충청": ["천안아산", "오송", "공주", "대전", "서대전", "논산"],
    "대구·경북": ["김천(구미)", "서대구", "동대구", "경산", "경주", "포항"],
    "경남·부산": ["밀양", "구포", "부산", "울산(통도사)", "진영", "창원중앙", "창원", "마산", "진주"],
    "호남": ["익산", "정읍", "광주송정", "나주", "목포", "전주", "남원", "곡성", "구례구", "순천", "여천", "여수EXPO"],
    "강원": ["강릉", "정동진"],
}

ALL: list[str] = [s for group in GROUPS.values() for s in group]

# 코레일이 함께 받아주는 다른 표기 → 표준 표기
ALIASES: dict[str, str] = {
    "김천구미": "김천(구미)",
    "신경주": "경주",
    "서울역": "서울",
    "울산": "울산(통도사)",
    "여수": "여수EXPO",
}


def canonical(name: str) -> str:
    """사용자·스킬이 넘긴 역명을 표준 표기로 맞춘다."""
    n = (name or "").strip()
    return ALIASES.get(n, n)


def is_known(name: str) -> bool:
    return canonical(name) in ALL
